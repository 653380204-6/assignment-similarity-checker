CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public."User" (
  auth_uid uuid NOT NULL DEFAULT gen_random_uuid(),
  email text NOT NULL,
  full_name text,
  CONSTRAINT User_pkey PRIMARY KEY (auth_uid)
);

CREATE TABLE IF NOT EXISTS public.documents_duplicate (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_name text NOT NULL,
  doc_id text,
  storage_path text,
  user_id uuid,
  status text,
  processing_mode integer,
  text_length bigint,
  image_count integer DEFAULT 0,
  removed_text_length bigint,
  error text,
  created_at timestamp without time zone DEFAULT now(),
  batch_id text,
  file_hash text,
  CONSTRAINT fk_documents_auth_user
    FOREIGN KEY (user_id) REFERENCES auth.users(id)
);

CREATE TABLE IF NOT EXISTS public.batch_files (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id text NOT NULL,
  user_id uuid NOT NULL,
  file_hash character varying NOT NULL,
  processing_mode integer NOT NULL,
  doc_id text NOT NULL,
  filename character varying NOT NULL,
  created_at timestamp with time zone DEFAULT now(),
  CONSTRAINT fk_batch_user
    FOREIGN KEY (user_id) REFERENCES public."User"(auth_uid),
  CONSTRAINT fk_batch_files_auth_user
    FOREIGN KEY (user_id) REFERENCES auth.users(id)
);
